import jsPDF from 'jspdf';
import { Complaint, isComplaintDelayed, isComplaintDone, UserAccount } from '../types';

export interface GenerateWeeklyReportOptions {
  complaints: Complaint[];
  managers: UserAccount[];
  adminUser: UserAccount;
  nowMs?: number;
}

export function generateWeeklyManagerReportPdf({
  complaints,
  managers,
  adminUser,
  nowMs = Date.now(),
}: GenerateWeeklyReportOptions): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = 210;
  const margin = 14;
  const contentWidth = pageWidth - margin * 2; // 182mm

  // Top decorative accent bar
  doc.setFillColor(37, 99, 235);
  doc.rect(0, 0, pageWidth, 4, 'F');

  // Header Title & Branding
  let currentY = 14;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(37, 99, 235);
  doc.text('WMD MANAGER PORTAL', margin, currentY);

  currentY += 6;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text('Manager Performance Report', margin, currentY);

  // Top Right Metadata
  const reportDate = new Date(nowMs).toLocaleDateString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
  });
  const reportTime = new Date(nowMs).toLocaleTimeString('en-GB', {
    hour: '2-digit',
    minute: '2-digit',
  });

  const metaRightX = pageWidth - margin;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(51, 65, 85);
  doc.text(`Date: ${reportDate} ${reportTime}`, metaRightX, 14, { align: 'right' });

  doc.setFont('helvetica', 'normal');
  doc.text(`Generated By: ${adminUser.name}`, metaRightX, 18.5, { align: 'right' });

  // Divider Line
  currentY += 5;
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.4);
  doc.line(margin, currentY, pageWidth - margin, currentY);

  // Overall Counts
  const totalCount = complaints.length;
  const doneCount = complaints.filter((c) => isComplaintDone(c)).length;
  const pendingCount = complaints.filter((c) => !isComplaintDone(c)).length;
  const delayedCount = complaints.filter((c) => isComplaintDelayed(c, nowMs)).length;

  // 1. Top Executive Summary Metric Cards
  currentY += 5;
  const cardGap = 3.5;
  const cardWidth = (contentWidth - cardGap * 3) / 4;
  const cardHeight = 18;

  const summaryCards = [
    { title: 'TOTAL QUERIES', value: totalCount, border: [203, 213, 225], top: [37, 99, 235], text: [15, 23, 42] },
    { title: 'COMPLETED', value: doneCount, border: [167, 243, 208], top: [16, 185, 129], text: [5, 150, 105] },
    { title: 'PENDING ACTION', value: pendingCount, border: [253, 230, 138], top: [245, 158, 11], text: [217, 119, 6] },
    { title: 'DELAYED (>48H)', value: delayedCount, border: [254, 202, 202], top: [239, 68, 68], text: [220, 38, 38] },
  ];

  summaryCards.forEach((c, idx) => {
    const cardX = margin + idx * (cardWidth + cardGap);
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(c.border[0], c.border[1], c.border[2]);
    doc.roundedRect(cardX, currentY, cardWidth, cardHeight, 1.5, 1.5, 'FD');

    doc.setFillColor(c.top[0], c.top[1], c.top[2]);
    doc.rect(cardX, currentY, cardWidth, 1.8, 'F');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(6.5);
    doc.setTextColor(100, 116, 139);
    doc.text(c.title, cardX + cardWidth / 2, currentY + 6, { align: 'center' });

    doc.setFontSize(12);
    doc.setTextColor(c.text[0], c.text[1], c.text[2]);
    doc.text(String(c.value), cardX + cardWidth / 2, currentY + 13.5, { align: 'center' });
  });

  currentY += cardHeight + 8;

  // 2. Section Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('Manager Performance Scorecards', margin, currentY);

  currentY += 4;

  // Prepare Manager Stats
  const managerStats = managers.map((mgr) => {
    const mgrComplaints = complaints.filter(
      (c) =>
        (c.managerId && c.managerId === mgr.id) ||
        (c.managerEmail && c.managerEmail.toLowerCase() === mgr.email.toLowerCase()) ||
        (c.managerName && c.managerName.toLowerCase() === mgr.name.toLowerCase())
    );

    const mTotal = mgrComplaints.length;
    const mDone = mgrComplaints.filter((c) => isComplaintDone(c)).length;
    const mPending = mgrComplaints.filter((c) => !isComplaintDone(c)).length;
    const mDelayed = mgrComplaints.filter((c) => isComplaintDelayed(c, nowMs)).length;
    const mRate = mTotal > 0 ? Math.round((mDone / mTotal) * 100) : 0;

    return { name: mgr.name, email: mgr.email, total: mTotal, done: mDone, pending: mPending, delayed: mDelayed, rate: mRate };
  });

  // 3. Render Manager KPI Cards (2 Columns Layout)
  const gridGap = 4;
  const mCardWidth = (contentWidth - gridGap) / 2; // ~89mm
  const mCardHeight = 28;

  managerStats.forEach((mgr, idx) => {
    const col = idx % 2;
    const row = Math.floor(idx / 2);
    const cardX = margin + col * (mCardWidth + gridGap);
    const cardY = currentY + row * (mCardHeight + gridGap);

    // Card Background Box
    doc.setFillColor(255, 255, 255);
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.3);
    doc.roundedRect(cardX, cardY, mCardWidth, mCardHeight, 2, 2, 'FD');

    // Left Border Highlight (Green if healthy, Red if has overdue queries)
    if (mgr.delayed > 0) {
      doc.setFillColor(239, 68, 68);
    } else {
      doc.setFillColor(16, 185, 129);
    }
    doc.rect(cardX, cardY + 2, 1.8, mCardHeight - 4, 'F');

    // Manager Name & Email
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(15, 23, 42);
    doc.text(mgr.name, cardX + 5, cardY + 6);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.8);
    doc.setTextColor(100, 116, 139);
    doc.text(mgr.email, cardX + 5, cardY + 9.5);

    // Resolution Badge
    const rateText = `${mgr.rate}%`;
    const isGood = mgr.rate >= 80;
    doc.setFillColor(isGood ? 236 : 254, isGood ? 253 : 242, isGood ? 245 : 242);
    doc.roundedRect(cardX + mCardWidth - 18, cardY + 3.5, 14, 5.5, 1, 1, 'F');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(isGood ? 5 : 220, isGood ? 150 : 38, isGood ? 105 : 38);
    doc.text(rateText, cardX + mCardWidth - 11, cardY + 7.3, { align: 'center' });

    // Progress bar (Done vs Pending vs Delayed)
    const barY = cardY + 12.5;
    const barWidth = mCardWidth - 10;
    const barHeight = 2.5;

    // Background track
    doc.setFillColor(241, 245, 249);
    doc.roundedRect(cardX + 5, barY, barWidth, barHeight, 0.8, 0.8, 'F');

    if (mgr.total > 0) {
      const doneW = (mgr.done / mgr.total) * barWidth;
      const delayedW = (mgr.delayed / mgr.total) * barWidth;

      // Green (Done)
      if (doneW > 0) {
        doc.setFillColor(16, 185, 129);
        doc.rect(cardX + 5, barY, doneW, barHeight, 'F');
      }
      // Red (Delayed)
      if (delayedW > 0) {
        doc.setFillColor(239, 68, 68);
        doc.rect(cardX + 5 + barWidth - delayedW, barY, delayedW, barHeight, 'F');
      }
    }

    // Bottom mini KPI numbers
    const kpiY = cardY + 20;
    const subColWidth = (mCardWidth - 10) / 4;

    const subKpis = [
      { label: 'TOTAL', val: mgr.total, isRed: false },
      { label: 'DONE', val: mgr.done, isRed: false },
      { label: 'PENDING', val: mgr.pending, isRed: false },
      { label: 'DELAYED', val: mgr.delayed, isRed: mgr.delayed > 0 },
    ];

    subKpis.forEach((sub, sIdx) => {
      const subX = cardX + 5 + sIdx * subColWidth + subColWidth / 2;
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(5.8);
      doc.setTextColor(148, 163, 184);
      doc.text(sub.label, subX, kpiY, { align: 'center' });

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      if (sub.isRed) {
        doc.setTextColor(220, 38, 38);
      } else {
        doc.setTextColor(30, 41, 59);
      }
      doc.text(String(sub.val), subX, kpiY + 4.5, { align: 'center' });
    });
  });

  // Calculate position after cards
  const totalRows = Math.ceil(managerStats.length / 2);
  currentY += totalRows * (mCardHeight + gridGap) + 4;

  // 4. Overdue Queries Priority Watchlist (Only drawn if overdue queries exist)
  const delayedComplaints = complaints.filter((c) => isComplaintDelayed(c, nowMs));
  if (delayedComplaints.length > 0 && currentY < 240) {
    doc.setFillColor(254, 242, 242);
    doc.setDrawColor(254, 202, 202);
    doc.roundedRect(margin, currentY, contentWidth, 24, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(220, 38, 38);
    doc.text('Priority Action Required: Queries Exceeding 48-Hours', margin + 4, currentY + 5.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.2);
    doc.setTextColor(71, 85, 105);

    delayedComplaints.slice(0, 3).forEach((dc, dIdx) => {
      const rowY = currentY + 11 + dIdx * 4;
      const snippet = dc.complaintText.length > 50 ? `${dc.complaintText.slice(0, 47)}...` : dc.complaintText;
      doc.text(`• Query #${dc.complaintId || dc.id} (${dc.managerName || 'Unassigned'}): ${snippet}`, margin + 5, rowY);
    });
  }

  // Footer (Standard bottom metadata)
  const footerY = 284;
  doc.setDrawColor(203, 213, 225);
  doc.setLineWidth(0.3);
  doc.line(margin, footerY, pageWidth - margin, footerY);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(6.8);
  doc.setTextColor(148, 163, 184);

  doc.text('WMD MANAGER PORTAL', margin, footerY + 5);
  doc.text('Page 1 of 1', pageWidth / 2, footerY + 5, { align: 'center' });

  // Save PDF
  const dateStr = new Date(nowMs).toISOString().slice(0, 10);
  doc.save(`Weekly_Manager_Summary_Report_${dateStr}.pdf`);
}